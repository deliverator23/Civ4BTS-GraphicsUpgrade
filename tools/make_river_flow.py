"""The river flow map built into GraphicsUpgrade (src/river_flow.h): for each place in BtS's river texture atlas
(Art/Terrain/Routes/Rivers/AllRiversSmaller.dds, 4 x 8 cells of 128 x 128 texels), which way the channel runs there and
how much the ripples may sway along it. The river shader sways the normal map's ripples back and forth along the
channel with it ([water] RiverShimmer).

  uv run --with pillow --with numpy --with scipy tools/make_river_flow.py <AllRiversSmaller.dds> [preview.png]

Texels: red, green = the channel's direction in texture space (u right, v down; x 0.5 + 0.5), blue = how much to sway
(1 in the water, 0 on the banks, off the river and near the cells' edges, where the next cell holds another piece of
river). The direction is the line the channel runs along, its sign kept the same along each channel (which way is
downstream isn't known; the sway goes both ways anyway)."""
import os
import sys
from collections import deque

import numpy as np
from PIL import Image
from scipy import ndimage

CELL = 128  # atlas cell, texels
SCALE = 4   # flow map texel = SCALE x SCALE atlas texels

src = sys.argv[1]
preview = sys.argv[2] if len(sys.argv) > 2 else None
base = np.asarray(Image.open(src).convert('RGBA'), np.float32) / 255
h, w = base.shape[:2]
assert w % CELL == 0 and h % CELL == 0, (w, h)

# Water: blue over red (the sand banks are the reverse), where the river is drawn.
water = (base[..., 3] > 0.5) & (base[..., 2] > base[..., 0] + 0.06)
water = ndimage.binary_opening(water, iterations=1)

# The channel's direction: across it, the distance to the banks changes fastest; the structure tensor of that gradient
# (smoothed) gives the line across, and the channel runs at right angles to it. Each cell on its own (no smoothing
# over its edges).
dist = ndimage.distance_transform_edt(water).astype(np.float32)
gy, gx = np.gradient(ndimage.gaussian_filter(dist, 1.0))
along = np.zeros((h, w, 2), np.float32)
for cy in range(0, h, CELL):
    for cx in range(0, w, CELL):
        sl = (slice(cy, cy + CELL), slice(cx, cx + CELL))
        jxx = ndimage.gaussian_filter(gx[sl] * gx[sl], 3.0)
        jxy = ndimage.gaussian_filter(gx[sl] * gy[sl], 3.0)
        jyy = ndimage.gaussian_filter(gy[sl] * gy[sl], 3.0)
        across = 0.5 * np.arctan2(2 * jxy, jxx - jyy)  # the eigenvector with the larger eigenvalue
        along[sl] = np.dstack([-np.sin(across), np.cos(across)])  # at right angles

# One sign along each channel: from a seed (heading down the texture) outwards, each texel takes the sign that agrees
# with the neighbour it was reached from. Within each cell, since cells are drawn apart.
seen = np.zeros((h, w), bool)
for cy in range(0, h, CELL):
    for cx in range(0, w, CELL):
        for sy, sx in zip(*np.nonzero(water[cy:cy + CELL, cx:cx + CELL])):
            sy, sx = sy + cy, sx + cx
            if seen[sy, sx]:
                continue
            if along[sy, sx, 1] < 0:
                along[sy, sx] *= -1
            seen[sy, sx] = True
            queue = deque([(sy, sx)])
            while queue:
                y, x = queue.popleft()
                for ny, nx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
                    if cy <= ny < cy + CELL and cx <= nx < cx + CELL and water[ny, nx] and not seen[ny, nx]:
                        if along[ny, nx] @ along[y, x] < 0:
                            along[ny, nx] *= -1
                        seen[ny, nx] = True
                        queue.append((ny, nx))

# How much to sway: in from the banks a little, and not within 3 texels of a cell's edge (full from 6: the sway
# reaches 3 texels, so it never reads the next cell).
amount = np.clip((dist - 1) / 3, 0, 1)
yy, xx = np.mgrid[0:h, 0:w]
edge = np.minimum(np.minimum(yy % CELL, CELL - 1 - yy % CELL), np.minimum(xx % CELL, CELL - 1 - xx % CELL))
amount *= np.clip((edge - 3) / 3, 0, 1)

# Down to the flow map's size: directions weighted by the amount, back to unit length.
fh, fw = h // SCALE, w // SCALE
weighted = (along * amount[..., None]).reshape(fh, SCALE, fw, SCALE, 2).sum(axis=(1, 3))
small_amount = amount.reshape(fh, SCALE, fw, SCALE).mean(axis=(1, 3))
length = np.linalg.norm(weighted, axis=2, keepdims=True)
small_along = np.where(length > 1e-6, weighted / np.maximum(length, 1e-6), 0)
rgba = np.dstack([np.round((small_along * 0.5 + 0.5) * 255), np.round(small_amount * 255),
                  np.full((fh, fw), 255)]).astype(np.uint8)
rgba[small_amount <= 0, :2] = 128

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'river_flow.h')
with open(out, 'w', newline='\r\n') as f:
    f.write('// Generated by tools/make_river_flow.py from BtS\'s AllRiversSmaller.dds: the river flow map (R, G = the\n'
            '// channel\'s direction in texture space x 0.5 + 0.5, B = how much the ripples sway, A = 255), rows top down.\n')
    f.write('#pragma once\n\n')
    f.write(f'const unsigned kRiverFlowWidth = {fw}, kRiverFlowHeight = {fh};\n')
    f.write('const unsigned char g_riverFlow[] = {\n')
    flat = rgba.reshape(-1)
    for i in range(0, len(flat), 32):
        f.write('    ' + ','.join(str(v) for v in flat[i:i + 32]) + ',\n')
    f.write('};\n')
print(f'{out}: {fw}x{fh}; swaying on {100 * (small_amount > 0.5).mean():.1f}% of it')

if preview:
    # Hue = the direction (doubled, so a channel reads one colour whichever way it points), brightness = the amount;
    # and a short tick each 8 texels along the channel.
    ang = np.arctan2(small_along[..., 1], small_along[..., 0])
    hue = (ang / np.pi) % 1
    rgb = np.stack([0.5 + 0.5 * np.cos(2 * np.pi * (hue - k / 3)) for k in range(3)], axis=2) * small_amount[..., None]
    img = Image.fromarray((rgb * 255).astype(np.uint8)).resize((w, h), Image.NEAREST)
    from PIL import ImageDraw
    d = ImageDraw.Draw(img)
    for y in range(SCALE, fh, 2):
        for x in range(SCALE, fw, 2):
            if small_amount[y, x] > 0.5:
                cx, cy = x * SCALE + SCALE / 2, y * SCALE + SCALE / 2
                ux, uy = small_along[y, x] * 6
                d.line([(cx - ux, cy - uy), (cx + ux, cy + uy)], fill=(255, 255, 255))
                d.point((cx + ux, cy + uy), fill=(255, 0, 0))
    img.save(preview)
